class CarnotMobiusLedger(nn.Module):
    """
    Computes the Carnot-Möbius Efficiency Limit for the Gyroidic Stack.
    Incorporates the topological friction generated by the ADMR solver's phase mismatch,
    and calculates thermal runaway.
    """
    def __init__(self, xi_shear: float = 0.1, p_cool_max: float = 1000.0, p_nuclear: float = 2000.0):
        super().__init__()
        self.xi_shear = xi_shear
        self.p_cool_max = p_cool_max
        self.p_nuclear = p_nuclear
        
    def forward(self, 
                lambda_vac: torch.Tensor, 
                lambda_pump: torch.Tensor, 
                admr_residues: torch.Tensor,
                depth_N: int,
                uncirculated_capital: Optional[torch.Tensor] = None,
                stagnation_velocity: Optional[float] = None) -> dict:
        """
        Calculates the stack efficiency and flags thermal runaway.
        Tracks uncirculated capital/potential as stack depth N.
        
        Args:
            lambda_vac: Base vacuum spectral density (Cold Sink)
            lambda_pump: Pumped highly excited state (Hot Reservoir)
            admr_residues: The phase mismatches (nabla epsilon_n) at boundaries. Shape: [N, ...]
            depth_N: The stack depth (N_crit check)
            uncirculated_capital: Uncirculated capital/potential tensor added to stack depth N
            stagnation_velocity: Rate of capital velocity flow (near 0 indicates terminal stagnation)
        """
        # 1. Ideal Carnot Geometric Efficiency
        # eta_ideal = 1 - (Lambda_vac / Lambda_pump)
        # Ensure lambda_pump is safely non-zero
        eta_ideal = 1.0 - (lambda_vac / (lambda_pump + 1e-8)).clamp(max=1.0)
        
        # 2. Topological Friction (Transmission coefficients)
        # tau_n = 1 - xi * |nabla epsilon_n|^2
        # We approximate nabla epsilon_n using the admr_residues magnitude
        nabla_eps_sq = torch.norm(admr_residues, dim=-1)**2
        
        # Average boundary perturbation variance
        sigma_eps_sq = nabla_eps_sq.mean()
        
        # Track uncirculated capital/potential as stack depth N
        effective_depth_N = depth_N
        if uncirculated_capital is not None:
            capital_potential = float(torch.norm(uncirculated_capital).item())
            effective_depth_N = depth_N + max(1, int(round(capital_potential)))

        # 3. Stack Efficiency
        # eta_stack = eta_ideal * exp(-N * xi * sigma_eps_sq)
        eta_stack = eta_ideal * torch.exp(-effective_depth_N * self.xi_shear * sigma_eps_sq)
        
        # 4. Thermodynamic Ledger
        p_waste = self.p_nuclear * (1.0 - eta_stack)
        thermal_runaway = p_waste > self.p_cool_max

        # 5. Critical Depth calculation (N_crit)
        # N_crit = (1 / (xi * sigma_eps_sq)) * ln(eta_ideal / (1 - (P_cool_max / P_nuclear)))
        cooling_ratio = self.p_cool_max / self.p_nuclear
        if cooling_ratio >= 1.0:
            n_crit = float('inf')
        else:
            log_arg = eta_ideal / (1.0 - cooling_ratio)
            # Safe log
            log_arg = log_arg.clamp(min=1e-6)
            n_crit = (1.0 / (self.xi_shear * sigma_eps_sq + 1e-8)) * torch.log(log_arg)

        n_crit_val = float(n_crit.item() if isinstance(n_crit, torch.Tensor) else n_crit)
        
        # Trigger irreversible N_crit thermal runaway flag when uncirculated potential stagnates
        is_stagnant = False
        if stagnation_velocity is not None and abs(stagnation_velocity) < 1e-4:
            is_stagnant = True
        elif uncirculated_capital is not None and effective_depth_N >= n_crit_val:
            is_stagnant = True

        irreversible_n_crit_runaway = False
        if (effective_depth_N >= n_crit_val) or (is_stagnant and effective_depth_N > 0.8 * n_crit_val):
            irreversible_n_crit_runaway = True
            thermal_runaway = torch.tensor(True, device=eta_stack.device if isinstance(eta_stack, torch.Tensor) else 'cpu')

        # 4.1 Broadcast directly to Centralized HardwareMonitor / Compute Affordance Chain
        try:
            from src.core.hardware_monitor import HardwareMonitor
            p_w_scalar = float(p_waste.item() if isinstance(p_waste, torch.Tensor) else p_waste)
            runaway_bool = bool(thermal_runaway.item() if isinstance(thermal_runaway, torch.Tensor) else thermal_runaway)
            eta_scalar = float(eta_stack.item() if isinstance(eta_stack, torch.Tensor) else eta_stack)
            HardwareMonitor().update_thermodynamics(
                p_waste=p_w_scalar,
                p_cool_max=float(self.p_cool_max),
                thermal_runaway=runaway_bool or irreversible_n_crit_runaway,
                eta_stack=eta_scalar,
                source="carnot_mobius"
            )
        except Exception:
            pass
            
        return {
            "eta_ideal": eta_ideal,
            "eta_stack": eta_stack,
            "p_waste": p_waste,
            "thermal_runaway": thermal_runaway,
            "irreversible_n_crit_runaway": irreversible_n_crit_runaway,
            "effective_depth_n": effective_depth_N,
            "effective_depth_N": effective_depth_N,
            "n_crit": n_crit,
            "topological_friction": sigma_eps_sq
        }

    def compute_parallel_sorting_entropy(
        self,
        omega_heads: torch.Tensor,
        gauge_circulation: torch.Tensor,
        euler_chi: Union[torch.Tensor, float] = 1.0,
        lambda_min: float = 1e-3,
        kappa_accel: float = 1.0,
        k_B: float = 1.0,
        efficiency_fn: Optional[Any] = None
    ) -> Dict[str, Any]:
        """
        Computes the Parallel Sorting Entropy:
        Delta S_{sort}^{||} = eta(N_{heads}) * sum_{h=1}^{N_{heads}} kappa_{accel} * [ k_B * ln(Omega_h) - oint_{gamma_h} (nabla x G_h) . dl + chi_h * lambda_{min}^{-1} ]

        Args:
            omega_heads: Microstate volume / permutation counts for each head [N_heads].
            gauge_circulation: Line integral of curl of gauge field around loop gamma_h [N_heads].
            euler_chi: Euler characteristic topological invariant for each head [N_heads] or scalar.
            lambda_min: Smallest non-zero Laplacian eigenvalue (> 0).
            kappa_accel: Curvature acceleration parameter (> 0).
            k_B: Boltzmann constant.
            efficiency_fn: Optional scaling function eta(N_heads). Defaults to 1 / sqrt(N_heads).

        Returns:
            Dictionary containing total delta_s_sort, per-head components, and thermodynamic diagnostics.
        """
        N_heads = omega_heads.shape[0] if omega_heads.dim() > 0 else 1
        
        # Scaling efficiency eta(N_heads)
        if efficiency_fn is not None:
            eta = float(efficiency_fn(N_heads))
        else:
            eta = 1.0 / math.sqrt(max(1, N_heads))

        # Safe log for microstate volumes: k_B * ln(Omega_h)
        safe_omega = torch.clamp(omega_heads, min=1e-8)
        boltzmann_term = k_B * torch.log(safe_omega)

        # Circulation term: - oint_{gamma_h} (nabla x G_h) . dl
        circ_term = -gauge_circulation

        # Euler characteristic term: chi_h * lambda_{min}^{-1}
        safe_lambda_min = max(1e-8, float(lambda_min))
        if isinstance(euler_chi, torch.Tensor):
            topo_term = euler_chi * (1.0 / safe_lambda_min)
        else:
            topo_term = float(euler_chi) * (1.0 / safe_lambda_min)

        # Per-head term: kappa_accel * [ k_B ln(Omega_h) - circ + chi * lambda_min^{-1} ]
        head_bracket = boltzmann_term + circ_term + topo_term
        head_entropy = kappa_accel * head_bracket

        # Total parallel sorting entropy
        delta_s_sort = eta * torch.sum(head_entropy)

        return {
            "delta_s_sort": delta_s_sort,
            "eta_heads": eta,
            "N_heads": N_heads,
            "boltzmann_entropy": boltzmann_term,
            "gauge_circulation": gauge_circulation,
            "topological_euler_term": topo_term,
            "per_head_entropy": head_entropy,
            "kappa_accel": kappa_accel,
            "lambda_min": safe_lambda_min
        }



class GENIUSOperator(nn.Module):
    """
    GENIUS Contortion Operator: Scale-Deformed Feedback Transformation Law.
    
    Formalizes the GENIUS contortion operator:
    Psi = (g_{mu nu}, K^alpha_{beta gamma}, T_{mu nu}, R)
    G[Psi] = ( dK/ds + div(T) + F(R) ) (x) J
    
    Where:
    - dK/ds: scale evolution of contortion tensor across renormalization scale s
    - div(T): anisotropic stress leakage into Riemannian geometry (divergence of stress tensor)
    - F(R): resonance feedback functional from the Carnot-Mobius / IHC acoustic cavity
    - J: angular tensor topology coupling (rotational gyro-precession operator)
    
    Measures mutual deformation of geometry, stress, resonance, and rotation across scale:
    'Reality = self-referential deformation of constraint.'
    """
    def __init__(self, dim: int = 16, resonance_coupling: float = 0.1):
        super().__init__()
        self.dim = dim
        self.resonance_coupling = resonance_coupling
        
        # Angular tensor topology coupling J (antisymmetric angular momentum generator)
        J_raw = torch.zeros(dim, dim)
        half = dim // 2
        for i in range(half):
            J_raw[2 * i, 2 * i + 1] = -1.0
            J_raw[2 * i + 1, 2 * i] = 1.0
        self.register_buffer("J_coupling", J_raw)

    def forward(
        self,
        contortion_K: torch.Tensor,
        stress_T: torch.Tensor,
        resonance_R: torch.Tensor,
        scale_ds: float = 0.05
    ) -> Dict[str, torch.Tensor]:
        """
        Applies G[Psi] transformation law.
        
        Args:
            contortion_K: [..., dim] or [..., dim, dim, dim] contortion tensor
            stress_T: [..., dim] or [..., dim, dim] anisotropic stress tensor
            resonance_R: [..., dim] or [..., 1] spectral resonance scalar/vector
            scale_ds: Scale increment ds
            
        Returns:
            Dict containing:
            - 'dK_ds': scale evolution rate of contortion
            - 'div_T': stress leakage into geometry
            - 'F_R': resonance feedback term
            - 'linear_sum': combined linear deformation
            - 'deformation_tensor': G[Psi] = (dK/ds + div(T) + F(R)) @ J
        """
        # 1. Scale evolution of contortion dK/ds
        if contortion_K.dim() > 1 and contortion_K.shape[-1] == self.dim:
            dK_ds = contortion_K * (1.0 / max(1e-4, scale_ds)) * 0.01
        else:
            dK_ds = contortion_K * 0.1
            
        # 2. Anisotropic stress leakage into geometry div(T)
        if stress_T.dim() >= 2 and stress_T.shape[-1] == self.dim and stress_T.shape[-2] == self.dim:
            div_T = torch.sum(stress_T, dim=-2)
        else:
            div_T = stress_T
            
        # 3. Resonance feedback term F(R)
        F_R = torch.tanh(resonance_R) * self.resonance_coupling
        if F_R.shape[-1] != self.dim:
            F_R = F_R.expand(*F_R.shape[:-1], self.dim)
            
        # Ensure compatible shape [..., dim]
        if dK_ds.dim() > div_T.dim():
            dK_proj = dK_ds.view(*div_T.shape)
        else:
            dK_proj = dK_ds
            
        linear_deformation = dK_proj + div_T + F_R
        
        # 4. Angular tensor topology coupling (x) J
        if linear_deformation.dim() == 1:
            deformation_tensor = linear_deformation @ self.J_coupling
        else:
            deformation_tensor = torch.matmul(linear_deformation, self.J_coupling)
            
        return {
            "dK_ds": dK_ds,
            "div_T": div_T,
            "F_R": F_R,
            "linear_sum": linear_deformation,
            "deformation_tensor": deformation_tensor
        }
